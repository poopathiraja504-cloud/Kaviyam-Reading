import fs from 'fs';
import path from 'path';
import { jsPDF } from 'jspdf';

const fontPath = 'public/fonts/NotoSansTamil.ttf';
let fontBase64 = null;
if (fs.existsSync(fontPath)) {
  fontBase64 = fs.readFileSync(fontPath).toString('base64');
}

function createStyledDoc() {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'pt',
    format: 'a4', // 595.28 x 841.89 pt
  });

  if (fontBase64) {
    doc.addFileToVFS('NotoSansTamil.ttf', fontBase64);
    doc.addFont('NotoSansTamil.ttf', 'NotoSansTamil', 'normal');
    doc.setFont('NotoSansTamil');
  }
  return doc;
}

function drawHeaderFooter(doc, title, issueText, pageNum, totalPages) {
  const w = doc.internal.pageSize.getWidth();
  const h = doc.internal.pageSize.getHeight();

  // Header line
  doc.setDrawColor(218, 165, 32); // gold
  doc.setLineWidth(1.5);
  doc.line(40, 45, w - 40, 45);

  doc.setFontSize(9);
  doc.setTextColor(100, 116, 139);
  doc.text(title, 40, 38);
  doc.text(issueText, w - 40, 38, { align: 'right' });

  // Footer line
  doc.setDrawColor(226, 232, 240);
  doc.setLineWidth(0.8);
  doc.line(40, h - 38, w - 40, h - 38);

  doc.setFontSize(9);
  doc.setTextColor(148, 163, 184);
  doc.text('காவியம் ரீடிங் · Kaviyam Tamil Digital Library', 40, h - 24);
  doc.text(`பக்கம் ${pageNum} / ${totalPages}`, w - 40, h - 24, { align: 'right' });
}

