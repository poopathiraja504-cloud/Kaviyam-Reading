// Data generator for 500 authentic Indian word finder puzzles
const PUZZLES = [];

function push(tTa, tEn, cTa, cEn, icon, words, wordsEn, hints, dTa, dEn) {
  const num = PUZZLES.length + 1;
  const id = `wf_${String(num).padStart(3, "0")}`;
  let difficulty = "Medium";
  if (num <= 100) difficulty = "Easy";
  else if (num <= 275) difficulty = "Medium";
  else if (num <= 425) difficulty = "Hard";
  else difficulty = "Expert";

  PUZZLES.push({
    id,
    number: num,
    titleTa: tTa,
    titleEn: tEn,
    categoryTa: cTa,
    categoryEn: cEn,
    categoryIcon: icon,
    difficulty,
    words: words.slice(0, 5),
    wordsEn: wordsEn.slice(0, 5),
    hints: hints.slice(0, 3),
    descriptionTa: dTa || `${tTa} சார்ந்த 5 முக்கிய சொற்களைக் கட்டத்தில் கண்டறியுங்கள்.`,
    descriptionEn: dEn || `Locate 5 key words related to ${tEn} in the puzzle grid.`
  });
}

